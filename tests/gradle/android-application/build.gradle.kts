import com.android.build.api.artifact.SingleArtifact
import com.android.build.api.variant.HostTestBuilder
import org.jetbrains.kotlin.gradle.dsl.JvmTarget
import java.util.zip.ZipFile

// Mirrors docs/docs/tutorial/1-tutorial-android.md: an Android application using the built-in
// Kotlin support of the Android Gradle Plugin, with the Android Gradle Plugin applied before the
// Gobley plugins.
plugins {
    alias(libs.plugins.android.application)
    id("dev.gobley.cargo")
    id("dev.gobley.uniffi")
    alias(libs.plugins.kotlin.atomicfu)
}

uniffi {
    bindgenFromPath(rootProject.layout.projectDirectory.dir("crates/rustine-uniffi-bindgen"))
    generateFromLibrary {
        packageName = "gobley.uniffi.tests.gradle.androidapplication"
    }
}

kotlin {
    compilerOptions {
        jvmTarget = JvmTarget.JVM_17
    }
}

dependencies {
    // A plain Android library without Gobley plugins.
    implementation(project(":tests:gradle:android-application-plain-dep"))
    testImplementation(libs.junit)
}

android {
    namespace = "dev.gobley.uniffi.tests.gradle.androidapplication"
    compileSdk = libs.versions.android.compileSdk.get().toInt()

    defaultConfig {
        applicationId = "dev.gobley.uniffi.tests.gradle.androidapplication"
        minSdk = 29
        targetSdk = libs.versions.android.targetSdk.get().toInt()
        versionCode = 1
        versionName = "1.0"
        ndk.abiFilters.add("arm64-v8a")
    }

    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }

    buildTypes {
        release {
            // Runs R8 with the ProGuard rules generated by the UniFFI plugin.
            isMinifyEnabled = true
            signingConfig = signingConfigs.getByName("debug")
        }
        // A custom build type. As its name doesn't contain `debug`, the release Rust library is
        // used in both the APK and the local unit tests.
        create("staging") {
            initWith(getByName("debug"))
            matchingFallbacks += "debug"
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
}

androidComponents {
    // Local unit tests are enabled only for the debug build type by default.
    beforeVariants(selector().withBuildType("staging")) { variantBuilder ->
        variantBuilder.hostTests[HostTestBuilder.UNIT_TEST_TYPE]?.enable = true
    }

    // Checks that each APK contains the Rust library only for the ABIs in abiFilters.
    onVariants { variant ->
        val apkDirectory = variant.artifacts.get(SingleArtifact.APK)
        val verifyApkTask = tasks.register("verify${variant.name.replaceFirstChar(Char::uppercase)}ApkJniLibs") {
            inputs.dir(apkDirectory)
            doLast {
                val apkFiles = apkDirectory.get().asFile.listFiles { file -> file.extension == "apk" }!!
                check(apkFiles.isNotEmpty()) { "No APK found in ${apkDirectory.get()}" }
                for (apkFile in apkFiles) {
                    val nativeLibraries = ZipFile(apkFile).use { zipFile ->
                        zipFile.entries().asSequence()
                            .map { it.name }
                            .filter { it.startsWith("lib/") }
                            .toSortedSet()
                    }
                    val expectedNativeLibraries = sortedSetOf(
                        "lib/arm64-v8a/libgobley_fixture_gradle_android_application.so",
                        "lib/arm64-v8a/libjnidispatch.so",
                    )
                    check(nativeLibraries == expectedNativeLibraries) {
                        "Unexpected native libraries in ${apkFile.name}: $nativeLibraries"
                    }
                }
            }
        }
        tasks.named("check") {
            dependsOn(verifyApkTask)
        }
    }
}
